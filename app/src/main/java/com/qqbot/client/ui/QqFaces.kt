    private val byQsid: Map<Int, QqFace> = all.associateBy { it.qsid }

    /** 按消息里的 faceId（QSid）取表情；找不到时返回 null */
    fun byFaceId(qsid: Int): QqFace? = byQsid[qsid]

    /** faceId -> EMCode，取不到时退回原值 */
    fun emcodeOf(qsid: Int): Int = byQsid[qsid]?.emcode ?: qsid

    /** 按图标 EMCode 反查名称 */
    fun nameOf(emcode: Int): String = all.firstOrNull { it.emcode == emcode }?.name.orEmpty()

    /**
     * 把表情转成 QQ 官方消息里的表情标签。
     * 格式：<faceType=1,faceId="QSid",ext="base64({"text":"名称"})">
     */
    fun insertTag(qsid: Int, name: String): String {
        val ext = android.util.Base64.encodeToString(
            "{\"text\":\"$name\"}".toByteArray(),
            android.util.Base64.NO_WRAP,
        )
        return "<faceType=1,faceId=\"$qsid\",ext=\"$ext\">"
    }
